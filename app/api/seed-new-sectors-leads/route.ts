function generateActivities(leadName: string, count: number) {
  const types = ['EMAIL', 'CALL', 'LINKEDIN', 'MEETING', 'NOTE'];
  const activities = [];

  const now = new Date();

  for (let i = 0; i < count; i++) {
    const type = types[Math.floor(Math.random() * types.length)];
    const daysAgo = Math.floor(Math.random() * 30) + 1;
    const activityDate = new Date(now.getTime() - (daysAgo * 24 * 60 * 60 * 1000));

    activities.push({
      type,
      content: `${type} activity with ${leadName}`,
      aiSummary: `Discussed project requirements and next steps with ${leadName}`,
      createdAt: activityDate,
    });
  }

  return activities.sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime());
}
