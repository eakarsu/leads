import { NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';

export async function GET() {
  try {
    console.log('🌱 Creating leads for 6 new business sectors...');

    // Get the new client companies
    const newClients = await prisma.clientCompany.findMany({
      where: {
        businessSector: {
          in: ['HOSPITALITY', 'FITNESS_WELLNESS', 'CONSTRUCTION', 'ECOMMERCE', 'INSURANCE', 'SOLAR_ENERGY']
        }
      },
      include: {
        users: true
      }
    });

    if (newClients.length === 0) {
      return NextResponse.json({ error: 'No new sector clients found' }, { status: 404 });
    }

    let totalLeadsCreated = 0;
    let totalActivitiesCreated = 0;

    for (const client of newClients) {
      console.log(`Creating leads for ${client.name} (${client.businessSector})`);

      // Create a campaign for this client
      const admin = await prisma.user.findFirst({ where: { role: 'ADMIN' } });

      const campaign = await prisma.campaign.create({
        data: {
          clientId: client.id,
          name: `${client.name} - Lead Generation Campaign`,
          description: `Lead generation campaign for ${client.industry}`,
          status: 'ACTIVE',
          channel: 'MULTI_CHANNEL',
          targetPersona: getTargetPersona(client.businessSector),
          ownerId: admin?.id || client.users[0]?.id,
          startDate: new Date(),
        },
      });

      // Generate 15 leads for this sector
      const leads = generateLeadsForNewSector(client.businessSector);

      for (const leadData of leads) {
        const lead = await prisma.lead.create({
          data: {
            campaignId: campaign.id,
            clientId: client.id,
            fullName: leadData.fullName,
            company: leadData.company,
            title: leadData.title,
            email: leadData.email,
            phone: leadData.phone,
            leadSource: 'AGENCY',
            status: leadData.status,
            qualificationScore: leadData.score,
            customFields: leadData.customFields,
          },
        });

        totalLeadsCreated++;

        // Create 5-10 activities for each lead
        const activityCount = Math.floor(Math.random() * 6) + 5;
        const activities = generateActivities(lead.fullName, activityCount);

        for (const activityData of activities) {
          await prisma.leadActivity.create({
            data: {
              leadId: lead.id,
              userId: client.users[0]?.id,
              type: activityData.type as any,
              content: activityData.content,
              aiSummary: activityData.aiSummary,
              createdAt: activityData.createdAt,
            },
          });
          totalActivitiesCreated++;
        }
      }
    }

    console.log(`✅ Created ${totalLeadsCreated} leads and ${totalActivitiesCreated} activities`);

    return NextResponse.json({
      message: 'Successfully created leads for new sectors',
      leadsCreated: totalLeadsCreated,
      activitiesCreated: totalActivitiesCreated,
    });

  } catch (error) {
    console.error('Seed error:', error);
    return NextResponse.json({ error: 'Seeding failed', details: String(error) }, { status: 500 });
  }
}

function getTargetPersona(sector: string): string {
  const personas: Record<string, string> = {
    HOSPITALITY: 'Hotel owners, restaurant managers, event venue operators',
    FITNESS_WELLNESS: 'Gym owners, yoga studio operators, wellness center managers',
    CONSTRUCTION: 'Homeowners seeking renovations, commercial property developers',
    ECOMMERCE: 'Online store owners, marketplace sellers, DTC brand owners',
    INSURANCE: 'Individuals and families seeking life, health, auto insurance',
    SOLAR_ENERGY: 'Homeowners and businesses interested in solar installation',
  };
  return personas[sector] || 'General prospects';
}

